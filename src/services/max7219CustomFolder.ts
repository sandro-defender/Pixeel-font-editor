/** Direct export of the Matrix Clock's contract-v1 custom font slot. */
import { MAX7219_CONTRACT_VERSION, type Max7219Package } from './max7219Export';
import { downloadBlob } from './persistence';

export interface CustomFolderFiles {
  'font.ttf': ArrayBuffer | Uint8Array;
  'LICENSE.txt': string;
  'font-info.json': string;
  'custom_font.yaml': string;
}

/** Minimal structural API, also usable with test doubles without browser globals. */
export interface CustomDirectoryHandle {
  getFileHandle(name: string, options: { create: true }): Promise<{
    createWritable(): Promise<{
      write(data: Blob): Promise<void>;
      close(): Promise<void>;
      abort(): Promise<void>;
    }>;
  }>;
}

const quote = (value: string) => "'" + value.replace(/'/g, "''") + "'";

export function buildCustomFolderFiles(pkg: Max7219Package): CustomFolderFiles {
  const { settings: s } = pkg;
  const info = {
    ...pkg.manifest,
    label: s.label,
    glyphs: s.glyphs,
    contractVersion: MAX7219_CONTRACT_VERSION,
    slug: s.slug,
    sourceTtfName: s.ttfFileName,
    ttfSha256: pkg.ttfSha256,
    installedAt: new Date().toISOString().replace(/\.\d{3}Z$/, 'Z'),
    fontId: 'font_custom_face',
    macro: 'MAX7219_CUSTOM_FACE',
    exportReportStatus: pkg.validation.ok ? 'PASS' : 'FAIL',
  };
  return {
    'font.ttf': pkg.ttf,
    'LICENSE.txt': s.licenseText,
    'font-info.json': JSON.stringify(info, null, 2) + '\n',
    'custom_font.yaml': `# Generated by Pixeel for Esphome-Max7219-Matrix-Clock.\n` +
      `# Re-run scripts/use_pixeel_font.py --folder custom to install.\n` +
      `font:\n  - id: font_custom_face\n    file:\n      type: local\n      path: font.ttf\n` +
      `    size: 8\n    bpp: 1\n    glyphs:\n      - ${quote(s.glyphs)}\n\n` +
      `esphome:\n  build_flags:\n    - -DMAX7219_CUSTOM_FACE\n\n` +
      `select:\n  - id: !extend clock_font\n    options:\n      - ${quote(s.label)}\n` +
      `    initial_option: ${quote(s.label)}\n`,
  };
}

/** Pick a directory on a user gesture; overwrite the slot, or download on older browsers. */
export async function writeCustomFolder(
  files: CustomFolderFiles,
  dirHandle?: CustomDirectoryHandle,
): Promise<'written' | 'downloaded' | 'cancelled'> {
  let dir = dirHandle;
  if (!dir && typeof window !== 'undefined' && 'showDirectoryPicker' in window && window.isSecureContext !== false) {
    try {
      dir = await (window as unknown as {
        showDirectoryPicker(options: { mode: 'readwrite' }): Promise<CustomDirectoryHandle>;
      }).showDirectoryPicker({ mode: 'readwrite' });
    } catch (err) {
      if (err && typeof err === 'object' && 'name' in err && err.name === 'AbortError') return 'cancelled';
      throw err;
    }
  }
  for (const [name, content] of Object.entries(files)) {
    // Copy typed arrays to an ArrayBuffer-backed view for Blob compatibility.
    const data = content instanceof Uint8Array ? new Uint8Array(content).buffer : content;
    const blob = new Blob([data], { type: name.endsWith('.ttf') ? 'font/ttf' : 'text/plain;charset=utf-8' });
    if (!dir) {
      downloadBlob(blob, name);
      continue;
    }
    const file = await dir.getFileHandle(name, { create: true });
    const writable = await file.createWritable();
    try {
      await writable.write(blob);
      await writable.close();
    } catch (err) {
      try { await writable.abort(); } catch { /* Keep the original write error. */ }
      throw err;
    }
  }
  return dir ? 'written' : 'downloaded';
}
